import { z } from 'zod';

///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////
//	CredentialTypes — the shape of the credential file
///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////

/**
 * The content of the credential file in the home folder of the user.
 */
export const CredentialSchema = z.object({
	/** The dev.to API key. */
	apiKey: z.string().min(1),
});

/**
 * The content of the credential file in the home folder of the user.
 */
export type Credential = z.infer<typeof CredentialSchema>;
